#!/usr/bin/env python3
"""Write a reproducible list of all papers that currently have benchmark results.

The output can be supplied directly to ``mark_reextract_papers.py mark-list``
to schedule a full forced LLM re-evaluation without clearing the database first.
"""

from __future__ import annotations

import argparse
import sys
from datetime import UTC, datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from backend.db import init_db, session_scope
from backend.models import Paper, Result


DEFAULT_OUTPUT = Path(__file__).resolve().parent.parent / "config" / "re_evaluate_all_papers.txt"


def paper_ids_with_results() -> list[str]:
    """Return stable arXiv IDs for papers that currently contribute result rows."""
    init_db()
    with session_scope() as session:
        rows = (
            session.query(Paper.arxiv_id)
            .join(Result, Result.paper_id == Paper.id)
            .filter(Paper.arxiv_id.isnot(None))
            .distinct()
            .order_by(Paper.arxiv_id)
            .all()
        )
    return [arxiv_id for (arxiv_id,) in rows if arxiv_id]


def write_list(output: Path) -> int:
    arxiv_ids = paper_ids_with_results()
    generated_at = datetime.now(UTC).isoformat()
    lines = [
        "# Papers with one or more benchmark-result rows, for a full LLM re-evaluation.",
        "# Generated by scripts/create_re_evaluation_list.py; one arXiv ID per line.",
        "# Mark with: uv run python scripts/mark_reextract_papers.py mark-list "
        f"--file {output} --yes --requeue",
        f"# Generated at: {generated_at}",
        "",
        *arxiv_ids,
        "",
    ]
    output.write_text("\n".join(lines), encoding="utf-8")
    return len(arxiv_ids)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    count = write_list(args.output)
    print(f"Wrote {count} paper ID(s) to {args.output}")


if __name__ == "__main__":
    main()
