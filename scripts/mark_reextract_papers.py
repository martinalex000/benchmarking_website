#!/usr/bin/env python3
"""Mark or re-extract papers affected by LaTeX table-parser changes.

Reads ``config/reextract_latex_papers.txt`` (generated by
``scripts/scan_latex_table_issues.py --write-list``).

Usage::

    uv run python scripts/mark_reextract_papers.py reextract 2411.05274
    uv run python scripts/mark_reextract_papers.py mark 2411.05274 --requeue
    uv run python scripts/mark_reextract_papers.py mark-list --dry-run
    uv run python scripts/mark_reextract_papers.py mark-list --yes --requeue
    uv run python scripts/mark_reextract_papers.py mark-list --yes --requeue --reason historical_result_loss
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from rich.console import Console
from rich.table import Table

from backend.config import normalize_arxiv_id
from backend.db import init_db, session_scope
from backend.models import Paper
from backend.todo_queue import add_todo_paper

console = Console()

_DEFAULT_LIST = Path(__file__).resolve().parent.parent / "config" / "reextract_latex_papers.txt"
_ARXIV_LINE = re.compile(r"^([0-9]{4}\.[0-9]{4,5}(?:v\d+)?)\b")


def parse_reextract_file(path: Path) -> list[str]:
    seen: set[str] = set()
    ordered: list[str] = []
    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.split("#", 1)[0].strip()
        if not line:
            continue
        match = _ARXIV_LINE.match(line)
        if not match:
            continue
        arxiv_id = normalize_arxiv_id(match.group(1))
        if arxiv_id in seen:
            continue
        seen.add(arxiv_id)
        ordered.append(arxiv_id)
    return ordered


def _title(arxiv_id: str) -> str:
    init_db()
    with session_scope() as session:
        row = session.query(Paper).filter_by(arxiv_id=arxiv_id).first()
        return row.title if row and row.title else ""


def _mark_ids(arxiv_ids: list[str], *, requeue: bool, reason: str) -> None:
    for arxiv_id in arxiv_ids:
        _created, message = add_todo_paper(
            arxiv_id,
            title=_title(arxiv_id) or None,
            reason=reason,
            added_by="mark_reextract_papers.py",
            is_manually_important=True,
            requeue=requeue,
        )
        console.print(message)

    console.print(
        f"\n[green]Marked {len(arxiv_ids)} paper(s) for LLM re-extraction.[/green]\n"
        "Run workers with [bold]--force[/bold] (see config/latex_table_reextract_server.txt)."
    )


def cmd_mark(args: argparse.Namespace) -> None:
    arxiv_id = normalize_arxiv_id(args.arxiv_id)
    if args.dry_run:
        console.print(f"[dim]Dry-run — would mark {arxiv_id}; nothing changed.[/dim]")
        return
    _mark_ids(
        [arxiv_id],
        requeue=args.requeue,
        reason=getattr(args, "reason", "reextract_latex_papers.txt"),
    )


def cmd_mark_list(args: argparse.Namespace) -> None:
    list_path = Path(args.file)
    if not list_path.is_file():
        console.print(f"[red]Re-extract list not found: {list_path}[/red]")
        sys.exit(1)

    arxiv_ids = parse_reextract_file(list_path)
    if not arxiv_ids:
        console.print(f"[yellow]No arXiv IDs found in {list_path}[/yellow]")
        return

    if args.dry_run:
        table = Table(show_header=True, header_style="bold", title="Would mark for re-extract")
        table.add_column("#", style="dim", justify="right")
        table.add_column("arXiv", style="cyan")
        table.add_column("Title")
        for index, arxiv_id in enumerate(arxiv_ids, start=1):
            table.add_row(str(index), arxiv_id, _title(arxiv_id)[:60])
        console.print(table)
        console.print(f"\n[dim]Dry-run — {len(arxiv_ids)} paper(s); nothing changed.[/dim]")
        return

    if not args.yes:
        console.print(
            f"[yellow]This will mark all {len(arxiv_ids)} papers in {list_path}.[/yellow]\n"
            "Re-run with [bold]--yes[/bold] to apply, or [bold]--dry-run[/bold] to preview."
        )
        return

    _mark_ids(arxiv_ids, requeue=args.requeue, reason=args.reason)


def cmd_reextract(args: argparse.Namespace) -> None:
    arxiv_id = normalize_arxiv_id(args.arxiv_id)
    _mark_ids([arxiv_id], requeue=True, reason="reextract_latex_papers.txt")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Re-extract one paper or explicitly mark papers for LaTeX re-extraction.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    sub = parser.add_subparsers(dest="command", required=True)

    reextract_parser = sub.add_parser(
        "reextract",
        help="Queue one arXiv paper for re-extraction by the todo dashboard",
    )
    reextract_parser.add_argument(
        "arxiv_id",
        type=normalize_arxiv_id,
        help="arXiv ID (for example, 2411.05274)",
    )
    mark_parser = sub.add_parser("mark", help="Mark one paper as manually important")
    mark_parser.add_argument(
        "arxiv_id",
        type=normalize_arxiv_id,
        help="arXiv ID (for example, 2411.05274)",
    )
    mark_parser.add_argument(
        "--requeue", action="store_true", help="Reset a finished row to pending"
    )
    mark_parser.add_argument("--dry-run", action="store_true", help="Show what would change")

    list_parser = sub.add_parser(
        "mark-list", help="Mark every paper in a re-extract list (requires --yes)"
    )
    list_parser.add_argument(
        "--file",
        type=Path,
        default=_DEFAULT_LIST,
        help=f"List path (default: {_DEFAULT_LIST})",
    )
    list_parser.add_argument(
        "--requeue",
        action="store_true",
        help="Reset done/failed/rejected rows back to pending",
    )
    list_parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Show what would be marked without changing the DB",
    )
    list_parser.add_argument(
        "--yes",
        action="store_true",
        help="Confirm marking every paper in the list",
    )
    list_parser.add_argument(
        "--reason",
        default="reextract_latex_papers.txt",
        help="Queue reason stored in todo_papers",
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    if args.command == "reextract":
        cmd_reextract(args)
    elif args.command == "mark":
        cmd_mark(args)
    elif args.command == "mark-list":
        cmd_mark_list(args)
    else:
        raise SystemExit(f"Unsupported command: {args.command}")


if __name__ == "__main__":
    main()
