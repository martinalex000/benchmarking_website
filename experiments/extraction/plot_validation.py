EXCLUDED_MODELS = {
    "meta-llama/Llama-3.1-8B-Instruct",
    "Qwen/Qwen3-Coder-30B-A3B-Instruct",
    "moonshotai/Kimi-K2.7-Code",
}


@dataclass(frozen=True)
class PaperModelSummary:
    paper: str
    model: str
    total_values: int
    shared_key_values: int
    key_unmatched_values: int
    exact_value_matches: int
    exact_value_unmatched: int
    exact_match_fraction: float
    duplicate_keys: int


def _load_outputs(run_dir: Path) -> tuple[str, dict[str, dict[str, ExtractionOutput]]]:
    report = json.loads((run_dir / "report.json").read_text(encoding="utf-8"))
    digest = str(report["manifest_digest"])
    outputs: dict[str, dict[str, ExtractionOutput]] = {}
    pattern = f"extraction-validation-{digest}-*/llm_output.yaml"
    for path in sorted(Path("papers").glob(f"*/extracted/experiments/{pattern}")):
        data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        results = data.get("results")
        model = str(data.get("model_used") or "").strip()
        if not isinstance(results, dict) or not model:
            continue
        outputs.setdefault(path.parents[3].name, {})[model] = ExtractionOutput.model_validate(
            results
        )
    return str(report["baseline_model"]), outputs


def _summary_for_paper(
    paper: str, model: str, outputs: dict[str, ExtractionOutput]
) -> PaperModelSummary:
    target = outputs[model]
    others = [output for other_model, output in outputs.items() if other_model != model]
    stats: ExactValueMatchStats = exact_value_match_stats(target, others)
    return PaperModelSummary(
        paper,
        model,
        stats.total_values,
        stats.shared_key_values,
        stats.key_unmatched_values,
        stats.exact_value_matches,
        stats.exact_value_unmatched,
        stats.exact_match_fraction,
        stats.duplicate_keys,
    )


def _aggregate(rows: list[PaperModelSummary]) -> dict[str, Any]:
    total = sum(row.total_values for row in rows)
    shared = sum(row.shared_key_values for row in rows)
    key_unmatched = sum(row.key_unmatched_values for row in rows)
    exact = sum(row.exact_value_matches for row in rows)
    return {
        "model": rows[0].model,
        "total_values": total,
        "shared_key_values": shared,
        "key_unmatched_values": key_unmatched,
        "exact_value_matches": exact,
        "exact_value_unmatched": sum(row.exact_value_unmatched for row in rows),
        "exact_match_fraction": exact / key_unmatched if key_unmatched else 0.0,
        "key_unmatched_fraction": key_unmatched / total if total else 0.0,
        "duplicate_keys": sum(row.duplicate_keys for row in rows),
    }


def _write_outputs(
    output_dir: Path, aggregate: list[dict[str, Any]], paper_rows: list[PaperModelSummary]
) -> None:
    with (output_dir / "extraction_validation_exact_value_summary.csv").open(
        "w", encoding="utf-8", newline=""
    ) as handle:
        writer = csv.DictWriter(handle, fieldnames=list(aggregate[0]))
        writer.writeheader()
        writer.writerows(aggregate)
    with (output_dir / "extraction_validation_exact_value_paper_model.csv").open(
        "w", encoding="utf-8", newline=""
    ) as handle:
        writer = csv.DictWriter(handle, fieldnames=list(asdict(paper_rows[0])))
        writer.writeheader()
        writer.writerows(asdict(row) for row in paper_rows)
    lines = [
        "% Generated by experiments/extraction/plot_validation.py",
        r"\begin{tabular}{lrrrrrr}",
        r"\toprule",
        "Model & Total & Shared key & Key-unmatched & Exact alternate & Unmatched & Exact fraction "
        + chr(92) * 2,
        r"\midrule",
    ]
    for row in aggregate:
        label = MODEL_LABELS.get(row["model"], row["model"]).replace("&", r"\&")
        lines.append(
            f"{label} & {row['total_values']:,} & {row['shared_key_values']:,} & {row['key_unmatched_values']:,} & {row['exact_value_matches']:,} & {row['exact_value_unmatched']:,} & {row['exact_match_fraction']:.1%} "
            + chr(92) * 2
        )
    lines.extend([r"\bottomrule", r"\end{tabular}", ""])
    (output_dir / "extraction_validation_exact_value_summary.tex").write_text(
        chr(10).join(lines), encoding="utf-8"
    )


def _pyplot() -> Any:
    os.environ.setdefault("MPLCONFIGDIR", "/tmp/benchmarking-extraction-matplotlib")
    Path(os.environ["MPLCONFIGDIR"]).mkdir(parents=True, exist_ok=True)
    import matplotlib

    matplotlib.use("Agg")
    matplotlib.rcParams.update(
        {"font.family": "DejaVu Sans", "font.size": 8, "pdf.fonttype": 42, "ps.fonttype": 42}
    )
    import matplotlib.pyplot as plt

    return plt


def _save(figure: Any, output_dir: Path, stem: str) -> None:
    figure.savefig(output_dir / f"{stem}.png", dpi=220, bbox_inches="tight")
    figure.savefig(output_dir / f"{stem}.pdf", bbox_inches="tight")


def _plot_summary(output_dir: Path, aggregate: list[dict[str, Any]]) -> None:
    plt = _pyplot()
    rows = sorted(aggregate, key=lambda row: row["exact_match_fraction"])
    labels = [MODEL_LABELS.get(row["model"], row["model"]) for row in rows]
    positions = list(range(len(rows)))
    figure, axes = plt.subplots(
        1, 2, figsize=(9.8, 3.8), gridspec_kw={"width_ratios": [1.4, 1], "wspace": 0.34}
    )
    shared = [row["shared_key_values"] for row in rows]
    alternate = [row["exact_value_matches"] for row in rows]
    unmatched = [row["exact_value_unmatched"] for row in rows]
    axes[0].barh(positions, shared, color="#4472C4", label="Shared key")
    axes[0].barh(
        positions, alternate, left=shared, color="#ED7D31", label="Exact value, alternate name"
    )
    axes[0].barh(
        positions,
        unmatched,
        left=[a + b for a, b in zip(shared, alternate, strict=True)],
        color="#A5A5A5",
        label="No exact value match",
    )
    axes[0].set(
        yticks=positions, yticklabels=labels, xlabel="Extracted values", title="Value accounting"
    )
    axes[0].legend(loc="lower right", frameon=False, fontsize=7)
    fractions = [row["exact_match_fraction"] for row in rows]
    axes[1].barh(positions, fractions, color="#ED7D31", height=0.58)
    axes[1].set(
        yticks=positions,
        yticklabels=[],
        xlim=(0, 1.04),
        xlabel="Exact alternate-name match fraction",
        title="Among key-unmatched values",
    )
    axes[1].xaxis.set_major_formatter(plt.FuncFormatter(lambda value, _: f"{value:.0%}"))
    for position, row in zip(positions, rows, strict=True):
        axes[1].text(
            min(row["exact_match_fraction"] + 0.015, 0.99),
            position,
            f"{row['exact_match_fraction']:.1%} (n={row['key_unmatched_values']:,})",
            va="center",
            fontsize=7,
        )
    for axis in axes:
        axis.grid(axis="x", color="#DCE1E6", linewidth=0.7)
        axis.set_axisbelow(True)
        axis.spines[["top", "right"]].set_visible(False)
        axis.tick_params(axis="y", length=0)
    figure.text(
        0.5,
        0.01,
        "Exact equality after scale normalization; matching ignores metric and model name.",
        ha="center",
        fontsize=7,
        color="#555555",
    )
    figure.subplots_adjust(bottom=0.14)
    _save(figure, output_dir, "extraction_validation_exact_value_matching_summary")
    plt.close(figure)


def _plot_scatter(output_dir: Path, rows: list[PaperModelSummary]) -> None:
    plt = _pyplot()
    import matplotlib.colors as mcolors

    models = [model for model in MODEL_LABELS if any(row.model == model for row in rows)]
    palette = list(mcolors.TABLEAU_COLORS.values())
    figure, axis = plt.subplots(figsize=(7.4, 4.5))
    for index, model in enumerate(models):
        selected = [row for row in rows if row.model == model]
        axis.scatter(
            [
                row.key_unmatched_values / row.total_values if row.total_values else 0.0
                for row in selected
            ],
            [row.exact_match_fraction for row in selected],
            s=[min(95, 18 + math.sqrt(row.total_values) * 1.8) for row in selected],
            color=palette[index % len(palette)],
            alpha=0.82,
            edgecolor="white",
            linewidth=0.45,
            label=MODEL_LABELS[model],
        )
    axis.set(
        xlim=(0, 1.02),
        ylim=(0, 1.02),
        xlabel="Fraction of values with an unmatched row key",
        ylabel="Exact alternate-name match fraction",
    )
    axis.xaxis.set_major_formatter(plt.FuncFormatter(lambda value, _: f"{value:.0%}"))
    axis.yaxis.set_major_formatter(plt.FuncFormatter(lambda value, _: f"{value:.0%}"))
    axis.grid(color="#DCE1E6", linewidth=0.7)
    axis.set_axisbelow(True)
    axis.spines[["top", "right"]].set_visible(False)
    axis.legend(loc="lower center", bbox_to_anchor=(0.5, -0.28), ncol=2, frameon=False)
    figure.subplots_adjust(bottom=0.27, left=0.11, right=0.98, top=0.97)
    _save(figure, output_dir, "extraction_validation_exact_value_matching_scatter")
    plt.close(figure)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--run-dir", type=Path, default=Path("experiments/extraction_validation/20260724T161948Z")
    )
    parser.add_argument("--output-dir", type=Path, default=None)
    args = parser.parse_args()
    output_dir = args.output_dir or args.run_dir
    output_dir.mkdir(parents=True, exist_ok=True)
    _reference_model, outputs_by_paper = _load_outputs(args.run_dir)
    models = sorted(
        {
            model
            for outputs in outputs_by_paper.values()
            for model in outputs
            if model in MODEL_LABELS and model not in EXCLUDED_MODELS
        }
    )
    paper_rows = [
        _summary_for_paper(paper, model, outputs)
        for paper, outputs in sorted(outputs_by_paper.items())
        for model in models
        if model in outputs
    ]
    aggregate = [_aggregate([row for row in paper_rows if row.model == model]) for model in models]
    _write_outputs(output_dir, aggregate, paper_rows)
    _plot_summary(output_dir, aggregate)
    _plot_scatter(output_dir, paper_rows)
    print(f"Wrote exact value-matching outputs to {output_dir}")
    for row in sorted(aggregate, key=lambda item: item["exact_match_fraction"]):
        print(
            f"{MODEL_LABELS[row['model']]}: {row['exact_value_matches']:,}/{row['key_unmatched_values']:,} exact ({row['exact_match_fraction']:.1%}); {row['exact_value_unmatched']:,} unmatched"
        )


if __name__ == "__main__":
    main()
